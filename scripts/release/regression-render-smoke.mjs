// regression-render-smoke.mjs — REL-002 area 6 helper (spawned by regression.sh).
//
// Proves the real production render path end-to-end (spec §21):
//   bundle() → selectComposition() → renderMedia() → ffprobe validation
// over TWO aspect ratios in one scripted run:
//   • 9:16  Short1Chess — an upstream shot (gen-registry output, real media
//     assets via staticFile: chess SVGs, Google Fonts, brand kit)
//   • 16:9  S01E01      — the episodic composition from the generated
//     episode registry (the shape every production episode renders through)
//
// The bundle entry (src/__regression_smoke__.tsx) and this runner are written
// by this file into the remotion project (its own npm node_modules) and
// removed afterwards — including on failure, so the repo tree never ends up
// dirty because of a smoke run. Renders land in a temp dir, never in the
// repo. Story text / plan JSON are data — parsed as Remotion props, never
// executed.
//
// Exit: 0 both renders ffprobe-valid · 1 any step failed (log has details).

// NOTE: this helper must NOT import @remotion/* — it lives in scripts/release/
// (inside the pnpm workspace, whose node_modules has no @remotion), and ESM
// resolves imports against the IMPORTING FILE's location, not the cwd. All
// @remotion/* imports belong in the generated RUNNER written into remotion/,
// where node_modules/@remotion actually exists.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, rmSync, existsSync, statSync } from 'node:fs';
import path from 'path';
import { fileURLToPath } from 'url';

const smokeDir = process.argv[2];
const logFile = process.argv[3];
if (!smokeDir || !logFile) {
  console.error('usage: node regression-render-smoke.mjs <smokeOutDir> <logFile>');
  process.exit(1);
}

// The remotion project is the repo's remotion/ dir — two levels up from
// scripts/release/. The runner executes FROM that directory so @remotion/*
// resolves against remotion/node_modules.
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const remotionRoot = path.resolve(scriptDir, '..', '..', 'remotion');
const repoRoot = path.resolve(remotionRoot, '..');
const mediaRoot = path.join(repoRoot, 'media');

const ENTRY = path.join(remotionRoot, 'src', '__regression_smoke__.tsx');
const RUNNER = path.join(remotionRoot, '__regression_smoke_render__.mjs');

// Remove both generated files no matter how this run ends (the repo tree
// must stay clean even when the smoke fails midway).
function cleanup() {
  rmSync(ENTRY, { force: true });
  rmSync(RUNNER, { force: true });
}

function fail(message) {
  console.error(`render-smoke: ${message}`);
  try { writeFileSync(logFile, readFileSync(logFile, 'utf8') + `\n${message}\n`); } catch { /* log best-effort */ }
  cleanup();
  process.exit(1);
}

if (!existsSync(path.join(remotionRoot, 'package.json'))) fail('remotion/ project not found');
if (!existsSync(path.join(remotionRoot, 'node_modules', '@remotion'))) {
  fail('remotion/node_modules/@remotion missing — run: cd remotion && npm ci');
}
if (!existsSync(mediaRoot)) fail('media/ public root missing — not an MMCS checkout?');

const manifest = JSON.parse(readFileSync(path.join(remotionRoot, 'src', 'shots.manifest.json'), 'utf8'));
const chess = manifest.find((s) => s.id === 'Short1Chess');
if (!chess) fail('Short1Chess missing from remotion/src/shots.manifest.json — smoke anchor shot gone');

const episodic = readFileSync(path.join(remotionRoot, 'src', 'episodic', 'episode-registry.gen.ts'), 'utf8');
if (!/compositionId.*S01E01/.test(episodic)) {
  fail('S01E01 missing from episode-registry.gen.ts — run: cd remotion && npm run gen');
}

// ---- one entry registering both compositions ------------------------------
writeFileSync(
  ENTRY,
  `// AUTO-GENERATED by scripts/release/regression-render-smoke.mjs — smoke-only,
// never committed. Registers the 9:16 smoke shot and the episodic 16:9
// composition so one bundle() pass serves both render smokes.
import React from 'react';
import { Composition, registerRoot } from 'remotion';
import Shot, { compositionConfig as shotCfg } from './shots/short-1/Short1Chess';
import { EpisodeComposition } from './episodic/EpisodeComposition';
import { episodeCompositions } from './episodic/episode-registry.gen';

const EpHost = ({ config }) => <EpisodeComposition config={config} />;

const RegressionSmokeRoot = () => (
  <>
    <Composition
      id={shotCfg.id}
      component={Shot}
      durationInFrames={Math.max(1, Math.round(shotCfg.durationInSeconds * shotCfg.fps))}
      fps={shotCfg.fps}
      width={shotCfg.width}
      height={shotCfg.height}
    />
    {episodeCompositions.map((c) => (
      <Composition
        key={c.compositionId}
        id={c.compositionId}
        component={EpHost}
        durationInFrames={c.durationInFrames}
        fps={c.fps}
        width={c.width}
        height={c.height}
        defaultProps={{ config: c }}
      />
    ))}
  </>
);

registerRoot(RegressionSmokeRoot);
`,
);

writeFileSync(
  RUNNER,
  `// AUTO-GENERATED by scripts/release/regression-render-smoke.mjs — smoke-only.
import { bundle } from '@remotion/bundler';
import { selectComposition, renderMedia } from '@remotion/renderer';
import path from 'path';

const remotionRoot = ${JSON.stringify(remotionRoot)};
const outDir = ${JSON.stringify(smokeDir)};
const serveUrl = await bundle({
  entryPoint: path.join(remotionRoot, 'src', '__regression_smoke__.tsx'),
  publicDir: path.join(${JSON.stringify(repoRoot)}, 'media'),
});

// 9:16 — upstream shot. 30 frames, scale 0.5 (540x960), h264 jpeg.
const c9 = await selectComposition({ serveUrl, id: 'Short1Chess' });
await renderMedia({
  serveUrl,
  composition: { ...c9, durationInFrames: 30 },
  outputLocation: path.join(outDir, '__smoke_9x16.mp4'),
  overwrite: true, codec: 'h264', frameRange: [0, 29], scale: 0.5,
  imageFormat: 'jpeg', crf: 18, onProgress: () => {},
});
console.log('  9:16  Short1Chess rendered');

// 16:9 — episodic composition (S01E01, generated registry, 1920x1080@30).
const c16 = await selectComposition({ serveUrl, id: 'S01E01' });
await renderMedia({
  serveUrl,
  composition: { ...c16, durationInFrames: 30 },
  outputLocation: path.join(outDir, '__smoke_16x9.mp4'),
  overwrite: true, codec: 'h264', frameRange: [0, 29], scale: 0.5,
  imageFormat: 'jpeg', crf: 18, onProgress: () => {},
});
console.log('  16:9  S01E01 rendered');
console.log('SMOKE_RENDER_OK');
`,
);

// ---- bundle + render via the remotion project's own node_modules -----------
const runner = spawnSync('node', [RUNNER, smokeDir], { cwd: remotionRoot, encoding: 'utf8', timeout: 480_000 });
let output = '';
output += runner.stdout ?? '';
output += runner.stderr ?? '';
writeFileSync(logFile, output);
if (runner.error) fail(`smoke runner failed to start: ${runner.error.message}`);
if (runner.status !== 0 || !output.includes('SMOKE_RENDER_OK')) {
  const tail = output.trim().split('\n').slice(-12).join('\n');
  fail(`smoke render failed (rc=${runner.status ?? 'signal'}):\n${tail}`);
}

// ---- ffprobe gate on both outputs (codec + dimensions) --------------------
function probe(file) {
  const res = spawnSync('ffprobe', [
    '-v', 'error', '-select_streams', 'v:0',
    '-show_entries', 'stream=codec_name,width,height',
    '-of', 'json', file,
  ], { encoding: 'utf8', timeout: 30_000 });
  if (res.status !== 0 || !res.stdout) return null;
  try {
    const streams = JSON.parse(res.stdout).streams ?? [];
    return streams[0] ?? null;
  } catch {
    return null;
  }
}

try {
  const checks = [
    { file: path.join(smokeDir, '__smoke_9x16.mp4'), width: 540, height: 960, label: '9:16 Short1Chess' },
    { file: path.join(smokeDir, '__smoke_16x9.mp4'), width: 960, height: 540, label: '16:9 S01E01' },
  ];
  for (const { file, width, height, label } of checks) {
    if (!existsSync(file) || statSync(file).size === 0) fail(`${label}: output missing/empty at ${file}`);
    const s = probe(file);
    if (!s) fail(`${label}: ffprobe could not read the output`);
    if (s.codec_name !== 'h264') fail(`${label}: expected h264, got ${s.codec_name}`);
    if (s.width !== width || s.height !== height) {
      fail(`${label}: expected ${width}x${height}, ffprobe reports ${s.width}x${s.height}`);
    }
    console.log(`  ${label}: ${s.width}x${s.height} ${s.codec_name} OK`);
  }
} finally {
  cleanup();
}

console.log('SMOKE_OK');
process.exit(0);
