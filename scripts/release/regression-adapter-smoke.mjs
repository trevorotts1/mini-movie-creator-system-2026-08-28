// regression-adapter-smoke.mjs — exercises the REAL render adapter.
//
// Why this exists (QC-B P0-1): scripts/release/regression-render-smoke.mjs
// proves the remotion/ project can bundle and render, but it imports
// `bundle`/`selectComposition`/`renderMedia` from @remotion/* DIRECTLY and
// drives them itself. It therefore proves nothing about
// packages/remotion-runtime/src/final-render/remotion-renderer.ts — the adapter
// the production pipeline is supposed to use. Until this script runs, the
// adapter had only ever been exercised against injected fakes.
//
// This one imports the BUILT adapter from the pnpm tree and renders through it,
// so a break in the adapter's own bundle → select → render chain fails the gate.
//
// Usage: node scripts/release/regression-adapter-smoke.mjs <outDir> <logFile>
import { spawnSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..', '..');
const remotionRoot = path.join(repoRoot, 'remotion');
const ADAPTER = path.join(
  repoRoot,
  'packages',
  'dist',
  'remotion-runtime',
  'src',
  'final-render',
  'remotion-renderer.js',
);
const ENTRY = path.join(remotionRoot, 'src', '__adapter_smoke__.tsx');
const COMPOSITION_ID = 'S01E01';

const outDir = process.argv[2];
if (!outDir) {
  console.error('usage: node regression-adapter-smoke.mjs <smokeOutDir> [logFile]');
  process.exit(2);
}
mkdirSync(outDir, { recursive: true });
const fail = (msg) => {
  console.error(`ADAPTER_SMOKE_FAIL: ${msg}`);
  process.exit(1);
};

if (!existsSync(ADAPTER)) {
  fail(`built adapter not found at ${ADAPTER} — run the package build first`);
}
if (!existsSync(path.join(remotionRoot, 'node_modules', '@remotion'))) {
  fail("remotion/node_modules/@remotion missing — run: cd remotion && npm ci");
}

// Reuse the headless browser the render smoke already downloaded rather than
// triggering a second ~190MB download. Remotion honours this env var.
const cachedBrowser = path.join(
  remotionRoot,
  'node_modules',
  '.remotion',
  'chrome-headless-shell',
  'mac-arm64',
  'chrome-headless-shell-mac-arm64',
  'chrome-headless-shell',
);
if (existsSync(cachedBrowser) && !process.env.REMOTION_BROWSER_EXECUTABLE) {
  process.env.REMOTION_BROWSER_EXECUTABLE = cachedBrowser;
}

// A minimal entry registering the same episodic composition the other smoke
// renders, written into remotion/ so the bundler resolves react/remotion from
// that project's node_modules.
writeFileSync(
  ENTRY,
  `// AUTO-GENERATED by scripts/release/regression-adapter-smoke.mjs — never committed.
import React from 'react';
import { Composition, registerRoot } from 'remotion';
import { EpisodeComposition } from './episodic/EpisodeComposition';
import { episodeCompositions } from './episodic/episode-registry.gen';

const Host = ({ config }) => <EpisodeComposition config={config} />;

const AdapterSmokeRoot = () => (
  <>
    {episodeCompositions.map((c) => (
      <Composition
        key={c.compositionId}
        id={c.compositionId}
        component={Host}
        durationInFrames={c.durationInFrames}
        fps={c.fps}
        width={c.width}
        height={c.height}
        defaultProps={{ config: c }}
      />
    ))}
  </>
);

registerRoot(AdapterSmokeRoot);
`,
);

const output = path.join(outDir, '__adapter_smoke.mp4');
const cleanup = () => {
  try {
    rmSync(ENTRY, { force: true });
  } catch {
    /* best effort */
  }
};

try {
  // Dynamic import so a load failure is reported as a smoke failure, not a
  // module-resolution crash before any output.
  let makeRemotionRenderAdapter;
  try {
    ({ makeRemotionRenderAdapter } = await import(ADAPTER));
  } catch (err) {
    fail(
      `could not import the built adapter (${err instanceof Error ? err.message : String(err)})`,
    );
  }

  const adapter = makeRemotionRenderAdapter({
    entryPoint: ENTRY,
    publicDir: path.join(repoRoot, 'media'),
  });

  const started = Date.now();
  const result = await adapter({
    compositionId: COMPOSITION_ID,
    output,
    fps: 30,
    width: 1920,
    height: 1080,
    durationInFrames: 30,
    codec: 'h264',
    scale: 0.5,
    imageFormat: 'jpeg',
    crf: 18,
    overwrite: true,
  });

  if (!existsSync(output)) fail(`adapter reported success but wrote no file at ${output}`);
  const probe = spawnSync(
    'ffprobe',
    [
      '-v',
      'error',
      '-select_streams',
      'v:0',
      '-show_entries',
      'stream=codec_name,width,height',
      '-of',
      'default=nw=1',
      output,
    ],
    { encoding: 'utf8' },
  );
  if (probe.status !== 0) fail(`ffprobe failed on the adapter output: ${probe.stderr}`);
  const codec = /codec_name=(\w+)/.exec(probe.stdout)?.[1];
  const width = /width=(\d+)/.exec(probe.stdout)?.[1];
  const height = /height=(\d+)/.exec(probe.stdout)?.[1];
  if (codec !== 'h264') fail(`expected h264, got ${codec}`);
  if (width !== '960' || height !== '540') {
    fail(`expected 960x540 at scale 0.5, got ${width}x${height}`);
  }

  console.log(`  adapter: ${COMPOSITION_ID} rendered through makeRemotionRenderAdapter`);
  console.log(`  ${width}x${height} ${codec} OK  (${result.renderSeconds.toFixed(1)}s)`);
  console.log('ADAPTER_SMOKE_OK');
  cleanup();
} catch (err) {
  cleanup();
  fail(err instanceof Error ? err.message : String(err));
}
